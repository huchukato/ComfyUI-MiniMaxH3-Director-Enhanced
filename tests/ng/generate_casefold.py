"""Regenerate the browser's casefold exceptions from the project's Python and Node runtimes.

Usage: python tests/ng/generate_casefold.py path/to/node.exe
The table pins Python's Unicode name semantics even when Node uses a newer Unicode release.
"""
import hashlib
import json
import subprocess
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
script = """const lower={};for(let i=0;i<=0x10ffff;i++){const c=String.fromCodePoint(i),l=c.toLowerCase();if(c!==l)lower[i]=l;}
process.stdout.write(JSON.stringify(lower));"""
lower = json.loads(subprocess.check_output([sys.argv[1], "-e", script], text=True, encoding="utf8"))
overrides = {code: chr(code).casefold() for code in range(0x110000) if chr(code).casefold() != lower.get(str(code), chr(code))}
digest = hashlib.sha256()
for code in range(0x110000):
    if not 0xd800 <= code <= 0xdfff:
        digest.update((chr(code).casefold() + "\0").encode("utf8"))
lines = ["// Generated by tests/ng/generate_casefold.py; Python Unicode %s." % unicodedata.unidata_version,
         "// Per-character lowercasing needs these exceptions to equal the compiler's casefold.", "const exceptions = new Map(["]
lines += ["  [0x%x, %s]," % (code, json.dumps(value, ensure_ascii=True)) for code, value in overrides.items()]
lines += ["]);", "", "export function caseFold(value) {",
          '  return Array.from(value,char=>exceptions.get(char.codePointAt(0))??char.toLowerCase()).join("");', "}"]
(ROOT / "js/ng/ng_casefold.js").write_text("\n".join(lines) + "\n", encoding="utf8")
(ROOT / "tests/ng/js/casefold_digest.json").write_text(json.dumps({"unicode": unicodedata.unidata_version,
                                                               "sha256": digest.hexdigest()}, indent=2) + "\n", encoding="utf8")
print("Generated %d Unicode casefold exceptions and complete scalar-value digest." % len(overrides))
